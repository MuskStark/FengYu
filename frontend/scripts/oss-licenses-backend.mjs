#!/usr/bin/env node
/**
 * Generates src/lib/ossBackendLicenses.ts — the backend (Maven runtime)
 * portion of the OSS disclosure. Runs `mvnw dependency:list` against the
 * FengYu module, then reads each artifact's POM from the local ~/.m2
 * repository for its <licenses> declaration (the authoritative statement the
 * upstream project ships).
 *
 * Re-run after backend dependency changes: node scripts/oss-licenses-backend.mjs
 */
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const frontendRoot = path.join(repoRoot, 'frontend')
const modulePom = path.join(repoRoot, 'FengYu', 'pom.xml')

const outputFile = path.join(os.tmpdir(), `fy-deps-${Date.now()}.txt`)
execFileSync(path.join(repoRoot, 'mvnw'), [
  '-q', '-f', modulePom, 'dependency:list', `-DoutputFile=${outputFile}`, '-DincludeScope=runtime',
], { stdio: ['ignore', 'ignore', 'inherit'] })

const coords = new Set()
for (const line of fs.readFileSync(outputFile, 'utf8').split('\n')) {
  const match = line.trim().match(/^([a-zA-Z0-9._-]+):([a-zA-Z0-9._-]+):jar:([a-zA-Z0-9._-]+):/)
  if (match) coords.add(`${match[1]}|${match[2]}|${match[3]}`)
}

const m2 = path.join(os.homedir(), '.m2', 'repository')

/**
 * Some upstream POMs omit <licenses> entirely (spring-data, logback, glassfish
 * jaxb, flyway, …). These overrides carry each artifact's publicly documented
 * license, keyed group:artifact — verified against the projects' own license
 * statements. POM declarations always win when present.
 */
const OVERRIDES = {
  'org.eclipse.angus:angus-activation': 'EDL-1.0',
  'org.eclipse.angus:angus-mail': 'EDL-1.0',
  'org.antlr:antlr-runtime': 'BSD-3-Clause',
  'org.antlr:antlr4-runtime': 'BSD-3-Clause',
  'net.bytebuddy:byte-buddy': 'Apache-2.0',
  'commons-logging:commons-logging': 'Apache-2.0',
  'org.simplejavamail:core-module': 'Apache-2.0',
  'org.simplejavamail:simple-java-mail': 'Apache-2.0',
  'com.github.bbottema:jetbrains-runtime-annotations': 'Apache-2.0',
  'org.flywaydb:flyway-core': 'Apache-2.0',
  'org.flywaydb:flyway-database-postgresql': 'Apache-2.0',
  'org.flywaydb:flyway-mysql': 'Apache-2.0',
  'com.sun.istack:istack-commons-runtime': 'EDL-1.0',
  'com.fasterxml.jackson.datatype:jackson-datatype-jdk8': 'Apache-2.0',
  'com.fasterxml.jackson.datatype:jackson-datatype-jsr310': 'Apache-2.0',
  'jakarta.xml.bind:jakarta.xml.bind-api': 'EDL-1.0',
  'org.glassfish.jaxb:jaxb-core': 'EDL-1.0',
  'org.glassfish.jaxb:jaxb-runtime': 'EDL-1.0',
  'org.glassfish.jaxb:txw2': 'EDL-1.0',
  'com.github.victools:jsonschema-generator': 'Apache-2.0',
  'com.github.victools:jsonschema-module-jackson': 'Apache-2.0',
  'com.github.victools:jsonschema-module-swagger-2': 'Apache-2.0',
  'org.slf4j:jul-to-slf4j': 'MIT',
  'org.slf4j:slf4j-api': 'MIT',
  'ch.qos.logback:logback-classic': 'EPL-1.0, LGPL-2.1',
  'ch.qos.logback:logback-core': 'EPL-1.0, LGPL-2.1',
  'com.google.protobuf:protobuf-java': 'BSD-3-Clause',
  'org.springframework.data:spring-data-commons': 'Apache-2.0',
  'org.springframework.data:spring-data-jpa': 'Apache-2.0',
  'io.swagger.core.v3:swagger-annotations': 'Apache-2.0',
  'io.swagger.core.v3:swagger-annotations-jakarta': 'Apache-2.0',
}

const entries = []
const unknown = []

for (const coord of coords) {
  const [group, artifact, version] = coord.split('|')
  const pomPath = path.join(m2, ...group.split('.'), artifact, version, `${artifact}-${version}.pom`)
  const override = OVERRIDES[`${group}:${artifact}`]
  let license = override ?? 'UNKNOWN'
  if (!override) {
    try {
      const pom = fs.readFileSync(pomPath, 'utf8')
      const block = pom.match(/<licenses>[\s\S]*?<\/licenses>/)?.[0]
      const names = [...(block?.matchAll(/<name>([^<]+)<\/name>/g) ?? [])].map(m => m[1].trim())
      if (names.length > 0) license = names.join(' OR ')
    } catch { /* no pom locally — declared unknown */ }
  }
  if (license === 'UNKNOWN') unknown.push(`${group}:${artifact}`)
  entries.push({ group, name: artifact, version, license })
}

entries.sort((a, b) => a.name.localeCompare(b.name))

const body = { generated: new Date().toISOString().slice(0, 10), count: entries.length, packages: entries }
const ts = `// GENERATED by scripts/oss-licenses-backend.mjs — do not edit by hand.
// Regenerate after backend dependency changes: node scripts/oss-licenses-backend.mjs
export interface OssBackendPackage {
  group: string
  name: string
  version: string
  license: string
}

export const ossBackendLicenses: { generated: string; count: number; packages: OssBackendPackage[] } = ${JSON.stringify(body, null, 2)}
`
fs.writeFileSync(path.join(frontendRoot, 'src', 'lib', 'ossBackendLicenses.ts'), ts)
console.log(`[oss-backend] ${entries.length} backend packages disclosed → src/lib/ossBackendLicenses.ts`)
if (unknown.length > 0) console.warn(`[oss-backend] license UNKNOWN for ${unknown.length}: ${unknown.slice(0, 8).join(', ')}${unknown.length > 8 ? '…' : ''}`)

#!/usr/bin/env node
/**
 * Generates src/lib/ossLicenses.ts — the OSS disclosure data the About page
 * renders. Authoritative source: each runtime dependency's own package.json
 * (license/version/homepage as published by the upstream project), read from
 * the local node_modules install.
 *
 * Re-run after dependency changes: node scripts/oss-licenses.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))
const entries = []
const missing = []

for (const name of Object.keys(pkg.dependencies ?? {})) {
  // Linked workspace packages (e.g. @infinia/plugin-sdk) are first-party, not disclosures.
  const depSpec = pkg.dependencies[name]
  if (depSpec.startsWith('link:')) continue
  const dir = path.join(root, 'node_modules', name)
  try {
    const meta = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'))
    entries.push({
      name: meta.name ?? name,
      version: meta.version ?? '',
      license: meta.license ?? 'UNKNOWN',
      homepage: meta.homepage ?? '',
    })
  } catch {
    missing.push(name)
  }
}

entries.sort((a, b) => a.name.localeCompare(b.name))

const body = {
  generated: new Date().toISOString().slice(0, 10),
  count: entries.length,
  packages: entries,
}

const ts = `// GENERATED by scripts/oss-licenses.mjs — do not edit by hand.
// Regenerate after dependency changes: node scripts/oss-licenses.mjs
export interface OssPackage {
  name: string
  version: string
  license: string
  homepage: string
}

export const ossLicenses: { generated: string; count: number; packages: OssPackage[] } = ${JSON.stringify(body, null, 2)}
`
fs.writeFileSync(path.join(root, 'src', 'lib', 'ossLicenses.ts'), ts)
console.log(`[oss-licenses] ${entries.length} packages disclosed → src/lib/ossLicenses.ts`)
if (missing.length > 0) {
  console.error(`[oss-licenses] missing from node_modules (run yarn install first): ${missing.join(', ')}`)
  process.exitCode = 1
}
